"""Executor Autoexecute heartbeat Lua script generator and multi-executor deployer."""
import os
import shutil

from rjcore import DEFAULT_AUTOEXEC, SHARED_AUTOEXEC, SHARED_WORKSPACE
from sysutils import scan_executor_dirs

HEARTBEAT_FILENAME = "rejoin_heartbeat.lua"

HEARTBEAT_LUA = r"""-- Auto-generated by rejoin_tool v2 (Multi-Executor Autoexecute Heartbeat)
local genv = (getgenv and getgenv()) or _G
if genv._RejoinToolLoaded then
    return
end
genv._RejoinToolLoaded = true

local Players = game:GetService("Players")
local HttpService = game:GetService("HttpService")
local GuiService = game:GetService("GuiService")
local CoreGui = game:GetService("CoreGui")
local VirtualUser = game:GetService("VirtualUser")
local TeleportService = game:GetService("TeleportService")
local StatsService = game:GetService("Stats")
local RunService = game:GetService("RunService")

if genv._RejoinFpsCap and setfpscap then
    pcall(setfpscap, genv._RejoinFpsCap)
end

pcall(function()
    if isfolder and makefolder and not isfolder("rejoin") then
        makefolder("rejoin")
    end
end)

local loadingDone = game:IsLoaded()
task.spawn(function()
    while not loadingDone do
        local lp = Players.LocalPlayer
        if lp and writefile then
            pcall(function()
                writefile("rejoin/hb_" .. tostring(lp.UserId) .. ".json", HttpService:JSONEncode({
                    time = os.time(),
                    placeId = game.PlaceId,
                    gameId = game.GameId,
                    placeVersion = game.PlaceVersion,
                    jobId = game.JobId,
                    userId = lp.UserId,
                    username = lp.Name,
                    status = "loading",
                    reason = "game_loading",
                    kicked = false,
                    kickMsg = "",
                    antiAfk = true,
                    fps = 0,
                    ping = 0,
                    playersCount = 0,
                    stats = {},
                }))
            end)
        end
        task.wait(4)
    end
end)

if not game:IsLoaded() then
    game.Loaded:Wait()
end
loadingDone = true

local player = Players.LocalPlayer
while not player do
    task.wait(0.2)
    player = Players.LocalPlayer
end

local hbPath = "rejoin/hb_" .. tostring(player.UserId) .. ".json"

local state = {
    status = "running",
    reason = "",
    kicked = false,
    kickMsg = "",
    antiAfk = true,
    stats = {},
}

local smoothedFps = 0
pcall(function()
    RunService.RenderStepped:Connect(function(dt)
        if dt and dt > 0 then
            smoothedFps = math.floor(1 / dt + 0.5)
        end
    end)
end)

local function readPingMs()
    local pingVal = 0
    pcall(function()
        local net = StatsService and StatsService:FindFirstChild("Network")
        local ssi = net and net:FindFirstChild("ServerStatsItem")
        local dp = ssi and ssi:FindFirstChild("Data Ping")
        if dp and dp.GetValue then
            pingVal = math.floor(tonumber(dp:GetValue()) or 0)
        end
    end)
    return pingVal
end

local function writeHeartbeat()
    local playersCount = 0
    pcall(function()
        playersCount = #Players:GetPlayers()
    end)
    local payload = {
        time = os.time(),
        placeId = game.PlaceId,
        gameId = game.GameId,
        placeVersion = game.PlaceVersion,
        jobId = game.JobId,
        userId = player.UserId,
        username = player.Name,
        status = state.status,
        reason = state.reason,
        kicked = state.kicked,
        kickMsg = state.kickMsg,
        antiAfk = state.antiAfk,
        fps = smoothedFps,
        ping = readPingMs(),
        playersCount = playersCount,
        stats = state.stats,
    }
    pcall(function()
        if writefile then
            writefile(hbPath, HttpService:JSONEncode(payload))
        end
    end)
end

local api = {}

function api.setStat(key, val)
    state.stats[tostring(key)] = val
end

function api.setStats(tbl)
    if type(tbl) == "table" then
        for k, v in pairs(tbl) do
            state.stats[tostring(k)] = v
        end
    end
end

function api.setGameInfo(tbl)
    api.setStats(tbl)
    writeHeartbeat()
end

function api.setStatus(st, reason)
    state.status = tostring(st or "running")
    state.reason = tostring(reason or "")
    writeHeartbeat()
end

function api.markDone(reason)
    state.status = "done"
    state.reason = tostring(reason or "done")
    writeHeartbeat()
end

function api.changeAccount(switchType, reason)
    local sw = tostring(switchType or "Custom")
    local rs = tostring(reason or sw)
    pcall(function()
        if writefile then
            writefile(player.Name .. ".txt", HttpService:JSONEncode({
                Type = sw,
                Completed = true,
                Reason = rs,
            }))
        end
    end)
    state.status = "done"
    state.reason = rs
    writeHeartbeat()
end

function api.requestRejoin(reason)
    state.status = "rejoin"
    state.reason = tostring(reason or "rejoin")
    writeHeartbeat()
end

function api.setAntiAfk(enabled)
    state.antiAfk = (enabled ~= false)
end

function api.flush()
    writeHeartbeat()
end

genv.RejoinTool = api
_G.RejoinTool = api

pcall(function()
    player.Idled:Connect(function()
        if state.antiAfk then
            pcall(function()
                VirtualUser:CaptureController()
                VirtualUser:ClickButton2(Vector2.new())
            end)
        end
    end)
end)

local function markKicked(msg)
    if not state.kicked then
        state.kicked = true
        state.kickMsg = tostring(msg or "disconnected")
        state.status = "kicked"
        state.reason = state.kickMsg
        writeHeartbeat()
    end
end

pcall(function()
    GuiService.ErrorMessageChanged:Connect(function(msg)
        if msg and msg ~= "" then
            local errCodeVal = 0
            pcall(function()
                if GuiService.GetErrorCode then
                    local ec = GuiService:GetErrorCode()
                    errCodeVal = (ec and ec.Value) or tonumber(ec) or 0
                end
            end)
            local low = string.lower(tostring(msg))
            if errCodeVal ~= 0 or string.find(low, "kick") or string.find(low, "disconnect") or string.find(low, "error code") or string.find(low, "lost connection") then
                markKicked(msg)
            end
        end
    end)
end)

pcall(function()
    TeleportService.TeleportInitFailed:Connect(function(_p, result, errMsg)
        local detail = tostring(errMsg or result or "teleport_failed")
        state.status = "rejoin"
        state.reason = "teleport_failed:" .. detail
        writeHeartbeat()
    end)
end)

pcall(function()
    local promptGui = CoreGui:FindFirstChild("RobloxPromptGui") or CoreGui:WaitForChild("RobloxPromptGui", 5)
    if promptGui then
        local overlay = promptGui:FindFirstChild("promptOverlay") or promptGui:WaitForChild("promptOverlay", 5)
        if overlay then
            overlay.ChildAdded:Connect(function(child)
                if child.Name == "ErrorPrompt" then
                    task.wait(0.2)
                    local msg = "ErrorPrompt"
                    pcall(function()
                        for _, d in ipairs(child:GetDescendants()) do
                            if d:IsA("TextLabel") and d.Name == "ErrorMessage" and d.Text ~= "" then
                                msg = d.Text
                                break
                            end
                        end
                    end)
                    markKicked(msg)
                end
            end)
        end
    end
end)

writeHeartbeat()
task.spawn(function()
    while task.wait(4) do
        writeHeartbeat()
    end
end)
"""


def sync_shared_assets(autoexec_dir, workspace_dir=None, shared_autoexec=None, shared_workspace=None):
    """Mirror files from shared/Autoexec and shared/Workspace into target executor folders."""
    synced = []
    s_ae = shared_autoexec or SHARED_AUTOEXEC
    s_ws = shared_workspace or SHARED_WORKSPACE
    if os.path.isdir(s_ae):
        os.makedirs(autoexec_dir, exist_ok=True)
        for fname in sorted(os.listdir(s_ae)):
            src = os.path.join(s_ae, fname)
            if os.path.isfile(src) and fname != HEARTBEAT_FILENAME:
                dst = os.path.join(autoexec_dir, fname)
                shutil.copy2(src, dst)
                synced.append(dst)
    if workspace_dir and os.path.isdir(s_ws):
        for root, _dirs, files in os.walk(s_ws):
            rel = os.path.relpath(root, s_ws)
            dst_dir = workspace_dir if rel == "." else os.path.join(workspace_dir, rel)
            os.makedirs(dst_dir, exist_ok=True)
            for fname in sorted(files):
                src = os.path.join(root, fname)
                dst = os.path.join(dst_dir, fname)
                shutil.copy2(src, dst)
                synced.append(dst)
    return synced


def deploy_heartbeat(
    autoexec_dir=DEFAULT_AUTOEXEC,
    extra_lua_path=None,
    workspace_dir=None,
    sync_shared=False,
    shared_autoexec=None,
    shared_workspace=None,
):
    """Write rejoin_heartbeat.lua (and optional profile/shared lua) into executor Autoexecute."""
    os.makedirs(autoexec_dir, exist_ok=True)
    deployed = []

    hb_dest = os.path.join(autoexec_dir, HEARTBEAT_FILENAME)
    with open(hb_dest, "w") as f:
        f.write(HEARTBEAT_LUA)
    deployed.append(hb_dest)

    if extra_lua_path:
        if not os.path.exists(extra_lua_path):
            raise FileNotFoundError(f"Lua file not found: {extra_lua_path}")
        stem = os.path.splitext(os.path.basename(extra_lua_path))[0]
        prof_dest = os.path.join(autoexec_dir, f"rejoin_profile_{stem}.lua")
        with open(extra_lua_path) as src, open(prof_dest, "w") as dst:
            dst.write(src.read())
        deployed.append(prof_dest)

    if sync_shared:
        deployed.extend(sync_shared_assets(autoexec_dir, workspace_dir, shared_autoexec, shared_workspace))

    return deployed


def deploy_all_executors(
    extra_lua_path=None,
    packages=None,
    sdcard_root="/storage/emulated/0",
    sync_shared=False,
    shared_autoexec=None,
    shared_workspace=None,
):
    """Deploy heartbeat (+ optional profile & shared scripts) across all detected executor directories."""
    entries = []
    seen = set()
    pkg_list = list(packages or [])
    if not pkg_list:
        pkg_list = [None]
    for p in pkg_list:
        for entry in scan_executor_dirs(pkg=p, sdcard_root=sdcard_root):
            ae = entry["autoexec"]
            if ae not in seen:
                seen.add(ae)
                entries.append(entry)

    all_deployed = []
    for entry in entries:
        all_deployed.extend(
            deploy_heartbeat(
                entry["autoexec"],
                extra_lua_path=extra_lua_path,
                workspace_dir=entry.get("workspace"),
                sync_shared=sync_shared,
                shared_autoexec=shared_autoexec,
                shared_workspace=shared_workspace,
            )
        )
    return all_deployed
